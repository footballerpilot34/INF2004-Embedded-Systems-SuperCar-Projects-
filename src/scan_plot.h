/* Lightweight dashboard Canvas plot; no external dependencies. */
#ifndef SCAN_PLOT_H
#define SCAN_PLOT_H
static char const g_scan_script[] =
    "(function(){\n"
    "'use strict';\n"
    "var data=null,canvas=document.getElementById('uscan');\n"
    "function drawScan(d){\n"
    " data=d;\n"
    " ['scanNow','scanTest'].forEach(function(id){document.getElementById(id).disabled=d.active||!d.can_scan});\n"
    " var scale=window.devicePixelRatio||1,w=canvas.clientWidth||320,h=240;\n"
    " canvas.width=Math.round(w*scale);canvas.height=Math.round(h*scale);\n"
    " canvas.style.height=h+'px';\n"
    " var x=canvas.getContext('2d');x.scale(scale,scale);\n"
    " var L=54,R=16,T=22,B=42,pw=w-L-R,ph=h-T-B;\n"
    " var maximum=100;\n"
    " d.points.forEach(function(p){if(p[1]!==null)maximum=Math.max(maximum,p[1])});\n"
    " maximum=Math.ceil(maximum/100)*100;\n"
    " function px(a){return L+(a-d.min)/(d.max-d.min)*pw}\n"
    " function py(r){return T+(1-r/maximum)*ph}\n"
    " x.fillStyle='#151a22';x.fillRect(0,0,w,h);x.font='12px sans-serif';\n"
    " x.strokeStyle='#394352';x.fillStyle='#cbd5e1';\n"
    " for(var i=0;i<=4;i++){\n"
    "  var v=maximum*i/4,y=py(v);\n"
    "  x.beginPath();x.moveTo(L,y);x.lineTo(w-R,y);x.stroke();\n"
    "  x.textAlign='right';x.fillText(Math.round(v),L-6,y+4);\n"
    " }\n"
    " x.textAlign='center';\n"
    " for(var a=d.min;a<=d.max;a+=Math.max(d.step,(d.max-d.min)/6)){\n"
    "  x.fillText(Math.round(a),px(a),h-B+18);\n"
    " }\n"
    " x.fillText('Servo angle (degrees)',L+pw/2,h-4);\n"
    " x.textAlign='left';x.fillText('Distance (mm)',L,14);\n"
    " var prev=null;\n"
    " d.points.forEach(function(p){\n"
    "  if(p[1]===null){prev=null;return}\n"
    "  if(prev&&Math.abs(p[0]-prev[0])<=d.step){\n"
    "   x.strokeStyle='#58d8ff';x.beginPath();x.moveTo(px(prev[0]),py(prev[1]));\n"
    "   x.lineTo(px(p[0]),py(p[1]));x.stroke();\n"
    "  }\n"
    "  x.fillStyle=p[2]===3?'#fc3':'#58d8ff';\n"
    "  x.beginPath();x.arc(px(p[0]),py(p[1]),3,0,Math.PI*2);x.fill();prev=p;\n"
    " });\n"
    " [[d.left,'Left','#ff8a80'],[d.right,'Right','#b5ef8a']].forEach(function(e){\n"
    "  if(e[0]===null)return;\n"
    "  x.strokeStyle=e[2];x.fillStyle=e[2];x.setLineDash([5,4]);\n"
    "  x.beginPath();x.moveTo(px(e[0]),T);x.lineTo(px(e[0]),h-B);x.stroke();\n"
    "  x.setLineDash([]);x.textAlign= e[1]==='Left'?'left':'right';\n"
    "  x.fillText(e[1]+' '+e[0].toFixed(1)+' deg',px(e[0]),T+13);\n"
    " });\n"
    " document.getElementById('usstate').textContent=d.state;\n"
    " function edge(a,s){return a===null?'not observed':a.toFixed(1)+' deg ('+s+')'}\n"
    " document.getElementById('usresult').textContent=\n"
    "  'Left: '+edge(d.left,d.ls)+'; Right: '+edge(d.right,d.rs)+\n"
    "  '; Corrected estimate: '+(d.corrected_width==null?'unknown':d.corrected_width+' mm')+\n"
    "  (d.width_fallback?' (150 mm fallback)':' (reliable calibrated reading)')+\n"
    "  '; Raw geometric width: '+(d.width===null?'unavailable':d.width+' mm')+\n"
    "  '; Calibrated obstacle width: '+(d.calibrated_width==null?\n"
    "   (d.calibration_enabled?'unknown':'disabled'):d.calibrated_width+' mm')+\n"
    "  (d.estimated?'. Clearance unverified.':'. Background echoes verified; corridor unverified.');\n"
    "}\n"
    "function poll(){\n"
    " var controller=window.AbortController?new AbortController():null,timer;\n"
    " var timeout=new Promise(function(_,reject){timer=setTimeout(function(){\n"
    "  if(controller)controller.abort();reject(new Error('Scan data timeout'));\n"
    " },4000)});\n"
    " Promise.race([fetch('/scan',controller?{signal:controller.signal}:{}).then(function(r){\n"
    "  if(!r.ok)throw new Error('HTTP '+r.status);return r.json();\n"
    " }),timeout]).then(function(d){\n"
    "  clearTimeout(timer);drawScan(d);setTimeout(poll,d.active?250:1000);\n"
    " }).catch(function(){\n"
    "  clearTimeout(timer);document.getElementById('usstate').textContent='Failed: connection lost';\n"
    "  setTimeout(poll,1000);\n"
    " });\n"
    "}\n"
    "window.addEventListener('resize',function(){if(data)drawScan(data)});\n"
    "poll();\n"
    "})();\n";
#endif
